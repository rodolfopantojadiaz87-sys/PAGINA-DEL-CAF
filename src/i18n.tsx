export function translateText(text: string, language: Language, values?: Values): string {
  const translated = language === 'pt' ? portuguese[text] ?? text : text
  if (!values) return translated
  return translated.replace(/\{([^}]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  )
}

export function getLocale(language: Language): string {
  return language === 'pt' ? 'pt-BR' : 'es'
}

export function getProcessLabel(process: string, language: Language): string {
  const labels: Record<string, string> = {
    RESIDENCIA: 'Residencia',
    'CAMBIO DE ENDEREZO': 'Cambio de domicilio',
    DESARCHIVAMENTO: 'Desarchivamiento',
    CPF: 'CPF',
    RNM: 'RNM',
    RENOVACION: 'Renovación',
    'ELABORACION DE CURRICULON': 'Elaboración de currículum',
  }
  const label = labels[process] ?? process
  return translateText(label, language)
}

